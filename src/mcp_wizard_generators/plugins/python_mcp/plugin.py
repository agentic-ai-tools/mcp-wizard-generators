    def _pyproject(self, pkg: str, ctx: GenerateContext) -> str:
        dist = pkg.replace("_", "-")
        return dedent(
            f"""\
            [build-system]
            requires = ["hatchling>=1.25"]
            build-backend = "hatchling.build"

            [project]
            name = "{dist}"
            version = "0.1.0"
            description = "Generated MCP server for {ctx.ir.title}"
            requires-python = ">=3.11"
            dependencies = [
              "mcp>=2.0.0,<3",
              "httpx>=0.27",
            ]

            [project.scripts]
            {dist} = "{pkg}.server:main"

            [tool.hatch.build.targets.wheel]
            packages = ["src/{pkg}"]
            """
        )

    def _requirements(self) -> str:
        return "mcp>=2.0.0,<3\nhttpx>=0.27\n"

    def _env_example(self, ctx: GenerateContext) -> str:
        base = ctx.ir.servers[0] if ctx.ir.servers else "https://api.example.com"
        lines = [
            f"API_BASE_URL={base}",
            "# Auth mode from wizard security config: " + ctx.security.auth_mode,
        ]
        if ctx.security.auth_mode == "api_key":
            lines.extend(
                [
                    "API_KEY=replace-me",
                    "API_KEY_HEADER=X-API-Key",
                ]
            )
        elif ctx.security.auth_mode == "oauth2":
            lines.extend(
                [
                    "OAUTH_TOKEN_URL=",
                    "OAUTH_CLIENT_ID=",
                    "OAUTH_CLIENT_SECRET=",
                    "OAUTH_SCOPES=",
                ]
            )
        lines.append("MCP_TRANSPORT=stdio")
        return "\n".join(lines) + "\n"

    def _cursor_mcp_json(self, pkg: str, ctx: GenerateContext) -> str:
        base = ctx.ir.servers[0] if ctx.ir.servers else "https://api.example.com"
        server_key = re.sub(r"[^a-zA-Z0-9_-]+", "-", pkg).strip("-") or "generated-mcp"
        env: dict[str, str] = {"API_BASE_URL": base}
        if ctx.security.auth_mode == "api_key":
            env["API_KEY"] = "${API_KEY}"
            env["API_KEY_HEADER"] = "X-API-Key"
        config = {
            "mcpServers": {
                server_key: {
                    "command": "python",
                    "args": ["-m", pkg],
                    "env": env,
                }
            }
        }
        return json.dumps(config, indent=2) + "\n"

    def _init(self, ctx: GenerateContext) -> str:
        return (
            f'"""Generated MCP server for {ctx.ir.title}.\n\n'
            "Built with the official MCP Python SDK (MCPServer, mcp>=2).\n"
            '"""\n\n__version__ = "0.1.0"\n'
        )

    def _main_module(self, pkg: str) -> str:
        return dedent(
            f"""\
            \"\"\"Allow `python -m {pkg}` to start the MCP stdio server.\"\"\"

            from {pkg}.server import main

            if __name__ == "__main__":
                main()
            """
        )

    def _http_client(self, ctx: GenerateContext) -> str:
        auth_block = self._auth_header_block(ctx.security.auth_mode)
        return dedent(
            f'''\
            """HTTP client for the upstream OpenAPI base URL.

            Auth mode: {ctx.security.auth_mode}
            Secrets strategy: {ctx.security.secrets_strategy}
            """

            from __future__ import annotations

            import os
            from typing import Any

            import httpx


            def _headers() -> dict[str, str]:
                headers: dict[str, str] = {{"Accept": "application/json"}}
            {auth_block}
                return headers


            def request(
                method: str,
                path: str,
                *,
                params: dict[str, Any] | None = None,
                json_body: dict[str, Any] | None = None,
            ) -> Any:
                base = os.environ.get("API_BASE_URL", "").rstrip("/")
                if not base:
                    raise RuntimeError("API_BASE_URL is not set")
                url = f"{{base}}{{path}}"
                with httpx.Client(headers=_headers(), timeout=30.0) as client:
                    response = client.request(method.upper(), url, params=params, json=json_body)
                    response.raise_for_status()
                    if response.status_code == 204 or not response.content:
                        return {{"status": response.status_code}}
                    content_type = response.headers.get("content-type", "")
                    if "application/json" in content_type:
                        return response.json()
                    return {{"text": response.text, "status": response.status_code}}
            '''
        )

    def _auth_header_block(self, auth_mode: str) -> str:
        if auth_mode == "api_key":
            return indent(
                dedent(
                    """\
                    api_key = os.environ.get("API_KEY")
                    if api_key:
                        header_name = os.environ.get("API_KEY_HEADER", "X-API-Key")
                        headers[header_name] = api_key
                    """
                ),
                "    ",
            ).rstrip()
        if auth_mode == "oauth2":
            return indent(
                dedent(
                    """\
                    # Expect a pre-fetched bearer token in API_TOKEN for local use.
                    token = os.environ.get("API_TOKEN") or os.environ.get("OAUTH_ACCESS_TOKEN")
                    if token:
                        headers["Authorization"] = f"Bearer {token}"
                    """
                ),
                "    ",
            ).rstrip()
        return "    # authMode=none — no credential headers"

    def _server(self, pkg: str, ctx: GenerateContext, tools: list[ToolMapping]) -> str:
        tool_fns = "\n\n\n".join(self._tool_function(t) for t in tools) or (
            "# No operations selected."
        )
        title_literal = json.dumps(ctx.ir.title)
        return (
            dedent(
                f'''\
                """MCP stdio server — official Python SDK MCPServer (mcp 2.x).

                Primary import follows the mcp 2 migration guide:
                https://py.sdk.modelcontextprotocol.io/v2/migration/#fastmcp-renamed-to-mcpserver
                """

                from __future__ import annotations

                from typing import Any

                from {pkg}.client import request

                try:
                    from mcp.server.mcpserver import MCPServer as _MCP
                except ImportError:  # mcp 1.x only — fresh installs pin mcp>=2
                    from mcp.server.fastmcp import FastMCP as _MCP

                mcp = _MCP({title_literal})


                '''
            )
            + tool_fns
            + dedent(
                """


                def main() -> None:
                    mcp.run(transport="stdio")


                if __name__ == "__main__":
                    main()
                """
            )
        )

    def _tool_function(self, tool: ToolMapping) -> str:
        props = (tool.input_schema or {}).get("properties") or {}
        required = set((tool.input_schema or {}).get("required") or [])
        path_params = set(re.findall(r"\{([^{}]+)\}", tool.path))

        sig_parts: list[str] = []
        for name, schema in props.items():
            py_type = _JSON_TYPE_TO_PY.get(str(schema.get("type", "string")), "Any")
            if name in required:
                sig_parts.append(f"{name}: {py_type}")
            else:
                sig_parts.append(f"{name}: {py_type} | None = None")

        # Stable order: required first (already roughly schema order), keep schema order.
        signature = ", ".join(sig_parts)
        doc = tool.description.replace('"""', "'''")

        # Build path + leftover query/body kwargs
        format_map_items = ", ".join(f"{p}={p}" for p in sorted(path_params) if p in props)
        leftover = [n for n in props if n not in path_params]
        method = tool.method.upper()
        uses_body = method in {"POST", "PUT", "PATCH"}

        body_lines = [
            f'    path_template = "{tool.path}"',
        ]
        if path_params:
            if format_map_items:
                body_lines.append(f"    path = path_template.format({format_map_items})")
            else:
                body_lines.append("    path = path_template")
        else:
            body_lines.append("    path = path_template")

        if leftover:
            dict_items = ", ".join(f'"{n}": {n}' for n in leftover)
            body_lines.append(
                f"    payload = {{k: v for k, v in {{{dict_items}}}.items() if v is not None}}"
            )
            if uses_body:
                body_lines.append(
                    f'    return request("{method}", path, json_body=payload or None)'
                )
            else:
                body_lines.append(f'    return request("{method}", path, params=payload or None)')
        else:
            body_lines.append(f'    return request("{method}", path)')

        body = "\n".join(body_lines)
        desc_kw = json.dumps(tool.description)
        return (
            f"@mcp.tool(name={json.dumps(tool.tool_name)}, description={desc_kw})\n"
            f"def {tool.tool_name}({signature}) -> Any:\n"
            f'    """{doc}"""\n'
            f"{body}"
        )
