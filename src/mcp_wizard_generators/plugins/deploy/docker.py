"""``docker``: a generic container that serves streamable HTTP (design ADR-026).

Runs anywhere Docker runs; no cloud account is involved. With inbound JWT auth the
server checks tokens itself (``auth.py``, any OIDC provider). Without it the server
is reachable only from the host, because compose publishes the port on 127.0.0.1.
"""

from __future__ import annotations

import json
from urllib.parse import urlsplit

from mcp_wizard_generators.models import (
    DeploymentConfig,
    FileEntry,
    FileTree,
    GenerateContext,
    ServerCapabilities,
)
from mcp_wizard_generators.plugins.deploy import deploy_docs, github_actions, scripts
from mcp_wizard_generators.plugins.deploy.constants import (
    CONTAINER_PORT,
    CONTAINER_UID,
    PYTHON_IMAGE,
)

JWT_FEATURE = "jwt-auth"


def _yaml(value: str) -> str:
    """A YAML scalar: JSON strings are valid YAML and quote everything safely."""
    return json.dumps(value)


class DockerDeployment:
    key = "docker"
    display_name = "Docker (streamable HTTP)"
    requires = frozenset({"streamable-http"})
    iac_options = frozenset({"none"})
    ci_options = frozenset({"none", "github-actions"})
    supports_scripts = True
    supports_inbound_auth = True

    def validate(self, config: DeploymentConfig) -> None:
        if config.aws_region:
            raise ValueError("deployment 'docker' does not use aws_region")
        if config.inbound_auth.create_cognito:
            raise ValueError(
                "deployment 'docker' cannot create a Cognito user pool; point "
                "discovery_url at an existing provider (Cognito included) instead"
            )

    def server_features(self, config: DeploymentConfig) -> frozenset[str]:
        return frozenset({JWT_FEATURE}) if config.inbound_auth.mode == "jwt" else frozenset()

    def generate(self, ctx: GenerateContext, caps: ServerCapabilities) -> FileTree:
        jwt = JWT_FEATURE in caps.features
        entries = [
            FileEntry("Dockerfile", self._dockerfile(caps)),
            FileEntry(".dockerignore", self._dockerignore()),
            FileEntry("docker-compose.yml", self._compose(ctx, caps, jwt)),
            FileEntry("README.md", self._readme(ctx, caps, jwt)),
            FileEntry("DEPLOY.md", deploy_docs.docker_deploy_md(ctx, caps, jwt=jwt)),
        ]
        if ctx.deployment.ci == "github-actions":
            entries += [
                github_actions.ci_workflow(caps, image=True),
                github_actions.release_workflow(caps),
                github_actions.dependabot(["github-actions", "docker"]),
            ]
        if ctx.deployment.scripts:
            entries += [*scripts.docker_scripts(caps), scripts.gitattributes()]
        return FileTree(entries=entries, root_name=caps.package_name.replace("_", "-"))

    @staticmethod
    def _dockerfile(caps: ServerCapabilities) -> str:
        return dockerfile(caps)

    @staticmethod
    def _dockerignore() -> str:
        return dockerignore()

    @staticmethod
    def _compose(ctx: GenerateContext, caps: ServerCapabilities, jwt: bool) -> str:
        return _compose(ctx, caps, jwt)

    @staticmethod
    def _readme(ctx: GenerateContext, caps: ServerCapabilities, jwt: bool) -> str:
        return _readme(ctx, caps, jwt)


def dockerfile(
    caps: ServerCapabilities,
    *,
    deployment: str = "docker",
    guide: str = 'README: "Run with Docker"',
    auth_where: str = "docker-compose.yml",
    platform: str | None = None,
) -> str:
    """Two-stage, hash-locked, non-root image serving streamable HTTP. Shared with the
    AgentCore container target, which pins ``platform`` to linux/arm64."""
    lock = caps.lock_files[0]
    module = caps.entrypoint.split(":", 1)[0].rsplit(".", 1)[0]
    port = CONTAINER_PORT
    base = f"--platform={platform} {PYTHON_IMAGE}" if platform else PYTHON_IMAGE
    return f"""\
# syntax=docker/dockerfile:1
# Generated by mcp-wizard-generators (deployment: {deployment}). {guide}.

# --- build: install the hash-locked dependencies into a virtualenv ---------------
FROM {base} AS build
ENV PIP_NO_CACHE_DIR=1 PIP_DISABLE_PIP_VERSION_CHECK=1
WORKDIR /build
COPY {lock} ./
RUN python -m venv /opt/venv \\
 && /opt/venv/bin/pip install --require-hashes -r {lock}

# --- runtime: the virtualenv and the server source, as a non-root user -----------
FROM {base}
COPY --from=build /opt/venv /opt/venv
COPY src/ /app/src/
COPY generation-manifest.json /app/
WORKDIR /app
ENV PATH=/opt/venv/bin:$PATH \\
    PYTHONPATH=/app/src \\
    PYTHONDONTWRITEBYTECODE=1 \\
    PYTHONUNBUFFERED=1 \\
    MCP_TRANSPORT=streamable-http \\
    MCP_HOST=0.0.0.0 \\
    MCP_PORT={port} \\
    MCP_PATH=/mcp
# MCP_AUTH is set where the container runs ({auth_where}). Without it the
# server refuses to listen on 0.0.0.0, so the image never runs unprotected by accident.
USER {CONTAINER_UID}
EXPOSE {port}
HEALTHCHECK --interval=30s --timeout=5s --start-period=10s --retries=3 \\
  CMD ["python", "-c", "import socket; socket.create_connection(('127.0.0.1', {port}), 3).close()"]
CMD ["python", "-m", "{module}"]
"""


def dockerignore() -> str:
    return "\n".join(
        [
            "# Keep secrets, local environments and build junk out of the image.",
            ".env",
            ".env.*",
            "!.env.example",
            ".venv",
            "venv",
            ".git",
            ".cursor",
            "**/__pycache__",
            "**/*.pyc",
            ".pytest_cache",
            "tests",
            "",
        ]
    )


def _compose(ctx: GenerateContext, caps: ServerCapabilities, jwt: bool) -> str:
    service = caps.package_name.replace("_", "-")
    port = CONTAINER_PORT
    auth = ctx.deployment.inbound_auth
    if jwt:
        environment = [
            "      # Every request needs a bearer token from this identity provider.",
            f"      MCP_AUTH: {_yaml('jwt')}",
            f"      MCP_JWT_DISCOVERY_URL: {_yaml(auth.discovery_url)}",
            f"      MCP_JWT_AUDIENCES: {_yaml(','.join(auth.allowed_audiences))}",
            f"      MCP_JWT_CLIENTS: {_yaml(','.join(auth.allowed_clients))}",
            f"      MCP_JWT_SCOPES: {_yaml(','.join(auth.allowed_scopes))}",
        ]
    else:
        environment = [
            "      # No token checks: the port above is published on 127.0.0.1 only, so",
            "      # nothing outside this machine can connect. That binding is the",
            "      # protection; regenerate with JWT auth before exposing this server.",
            f"      MCP_AUTH: {_yaml('platform')}",
        ]
    return "\n".join(
        [
            "# Generated by mcp-wizard-generators (deployment: docker).",
            "# Run: docker compose up --build   (README: Run with Docker)",
            "services:",
            f"  {service}:",
            "    build: .",
            f"    image: {service}:local",
            "    ports:",
            "      # This machine only. Publish more widely only with JWT auth.",
            "      # Port taken? Set MCP_HOST_PORT in .env (for example 8001).",
            f"      - {_yaml('127.0.0.1:${MCP_HOST_PORT:-' + str(port) + '}:' + str(port))}",
            "    env_file:",
            "      # API_BASE_URL and upstream credentials; never baked into the image.",
            "      - path: .env",
            "        required: false",
            "    environment:",
            *environment,
            "    read_only: true",
            "    tmpfs:",
            "      - /tmp",
            "    cap_drop:",
            "      - ALL",
            "    security_opt:",
            f"      - {_yaml('no-new-privileges:true')}",
            "    restart: unless-stopped",
            "",
        ]
    )


def _readme(ctx: GenerateContext, caps: ServerCapabilities, jwt: bool) -> str:
    pkg = caps.package_name
    url = f"http://127.0.0.1:{CONTAINER_PORT}/mcp"
    lines = [
        "## Run with Docker",
        "",
        "`Dockerfile` builds a small image (pinned Python base image, hash-checked",
        "install, non-root user) that serves streamable HTTP on port "
        f"{CONTAINER_PORT}. `docker-compose.yml`",
        "runs it with a read-only filesystem, no Linux capabilities, and the port",
        "published on `127.0.0.1` only.",
        "",
        "1. Put `API_BASE_URL` and any upstream credentials in `.env`",
        "   (`cp .env.example .env`). Compose reads `.env`; the image never contains it.",
        "2. Build and start: `docker compose up --build`",
    ]
    if jwt:
        host = urlsplit(ctx.deployment.inbound_auth.discovery_url).hostname or ""
        lines += [
            f"3. Get an access token from your identity provider (`{host}`) for one of the",
            "   allowed audiences, clients or scopes in `docker-compose.yml`, then check:",
            "",
            "   ```bash",
            '   export MCP_BEARER_TOKEN=...   # PowerShell: $env:MCP_BEARER_TOKEN = "..."',
            f"   python -m {pkg}.verify --url {url}",
            "   ```",
            "",
            "Every request needs `Authorization: Bearer <token>`. The server checks the",
            "signature against the provider's published keys, the issuer, expiry, and the",
            "`MCP_JWT_*` settings in `docker-compose.yml`; change those to switch providers.",
            "Requests without a valid token get 401 (403 when the client or scopes are not",
            "allowed). Serve it over HTTPS (a reverse proxy or load balancer) before",
            "publishing the port beyond this machine.",
            "",
        ]
    else:
        lines += [
            f"3. Check: `python -m {pkg}.verify --url {url}`",
            "",
            "This server does **not** check tokens, so compose keeps it reachable from this",
            "machine only. To expose it, regenerate with the docker deployment and JWT",
            "auth (any OIDC identity provider).",
            "",
        ]
    return "\n".join(lines)
