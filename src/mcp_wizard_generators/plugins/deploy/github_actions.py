"""GitHub Actions workflows and Dependabot config for generated projects (ADR-026).

Shared by the deployment plugins. Every action is pinned to a commit SHA
(``constants.ACTIONS``), checkouts never keep the token, workflows get the least
permissions they need, and no event data is interpolated into shell commands.
"""

from __future__ import annotations

from mcp_wizard_generators.models import FileEntry, ServerCapabilities
from mcp_wizard_generators.plugins.deploy.agentcore_package import PACKAGE_SCRIPT, ZIP_PATH
from mcp_wizard_generators.plugins.deploy.constants import (
    ACTIONS,
    AGENTCORE_CODE_PYTHON,
    CI_PYTHON_VERSIONS,
    CONTAINER_PORT,
    TERRAFORM_VERSION,
    UV_VERSION,
)

CI_PATH = ".github/workflows/ci.yml"
RELEASE_PATH = ".github/workflows/release.yml"
DEPENDABOT_PATH = ".github/dependabot.yml"


def _module(caps: ServerCapabilities) -> str:
    return caps.entrypoint.split(":", 1)[0].rsplit(".", 1)[0]


def _checkout() -> list[str]:
    return [
        f"      - uses: {ACTIONS['actions/checkout']}",
        "        with:",
        "          persist-credentials: false",
    ]


def _setup_python(version: str) -> list[str]:
    return [
        f"      - uses: {ACTIONS['actions/setup-python']}",
        "        with:",
        f"          python-version: {version}",
    ]


def _install(lock: str, *, pytest: bool) -> list[str]:
    lines = [
        "      - name: Install (hash-checked)",
        "        run: |",
        f"          python -m pip install --require-hashes -r {lock}",
        "          python -m pip install --no-deps -e .",
    ]
    if pytest:
        lines.append('          python -m pip install "pytest>=8,<10"')
    return lines


def ci_workflow(caps: ServerCapabilities, *, image: bool, package: bool = False) -> FileEntry:
    """Test the server on every push and pull request; with ``image``, also build the
    container and call it over HTTP; with ``package``, build the AgentCore code zip."""
    module = _module(caps)
    lock = caps.lock_files[0]
    versions = ", ".join(f'"{v}"' for v in CI_PYTHON_VERSIONS)
    lines = [
        "# Generated by mcp-wizard-generators. Tests the MCP server on every push and PR.",
        "name: CI",
        "",
        "on:",
        "  push:",
        "    branches: [main]",
        "  pull_request:",
        "",
        "permissions:",
        "  contents: read",
        "",
        "jobs:",
        "  test:",
        "    runs-on: ubuntu-latest",
        "    strategy:",
        "      matrix:",
        f"        python-version: [{versions}]",
        "    steps:",
        *_checkout(),
        *_setup_python("${{ matrix.python-version }}"),
        *_install(lock, pytest=True),
        "      - name: Test (no network; the upstream API is mocked)",
        "        run: python -m pytest",
        "      - name: Check the exposed tools",
        f"        run: python -m {module}.verify",
    ]
    if image:
        url = f"http://127.0.0.1:{CONTAINER_PORT}/mcp"
        lines += [
            "",
            "  image:",
            "    needs: test",
            "    runs-on: ubuntu-latest",
            "    steps:",
            *_checkout(),
            *_setup_python(f'"{CI_PYTHON_VERSIONS[-1]}"'),
            *_install(lock, pytest=False),
            "      - name: Build the image",
            f"        run: docker build -t {caps.package_name.replace('_', '-')}:ci .",
            "      - name: Start it with MCP_AUTH=platform (this smoke test sends no token)",
            "        run: >-",
            "          docker run --detach --name mcp",
            f"          -p 127.0.0.1:{CONTAINER_PORT}:{CONTAINER_PORT}",
            "          -e API_BASE_URL=https://api.example.com",
            "          -e MCP_AUTH=platform",
            f"          {caps.package_name.replace('_', '-')}:ci",
            "      - name: Call it over streamable HTTP",
            "        run: |",
            "          for attempt in $(seq 1 30); do",
            f"            if python -m {module}.verify --url {url}; then exit 0; fi",
            '            echo "not ready yet (attempt $attempt)"; sleep 2',
            "          done",
            "          docker logs mcp",
            "          exit 1",
        ]
    if package:
        lines += [
            "",
            "  package:",
            "    needs: test",
            "    runs-on: ubuntu-latest",
            "    steps:",
            *_checkout(),
            *_setup_python(f'"{CI_PYTHON_VERSIONS[-1]}"'),
            *_setup_uv(),
            "      - name: Build the AgentCore code package (ARM64 wheels from the lock)",
            f"        run: python {PACKAGE_SCRIPT}",
        ]
    return FileEntry(CI_PATH, "\n".join(lines) + "\n")


def _setup_uv() -> list[str]:
    return [
        f"      - uses: {ACTIONS['astral-sh/setup-uv']}",
        "        with:",
        f'          version: "{UV_VERSION}"',
        "          enable-cache: false",
    ]


def release_workflow(caps: ServerCapabilities) -> FileEntry:
    """Build a multi-arch image and push it to GitHub Container Registry on a v* tag."""
    lines = [
        "# Generated by mcp-wizard-generators. Publishes the image to GitHub Container",
        "# Registry (ghcr.io/<owner>/<repo>) when you push a tag such as v1.0.0.",
        "name: Release image",
        "",
        "on:",
        "  push:",
        '    tags: ["v*"]',
        "  workflow_dispatch:",
        "",
        "permissions:",
        "  contents: read",
        "  packages: write",
        "",
        "jobs:",
        "  image:",
        "    runs-on: ubuntu-latest",
        "    steps:",
        *_checkout(),
        f"      - uses: {ACTIONS['docker/setup-qemu-action']}",
        f"      - uses: {ACTIONS['docker/setup-buildx-action']}",
        f"      - uses: {ACTIONS['docker/login-action']}",
        "        with:",
        "          registry: ghcr.io",
        "          username: ${{ github.actor }}",
        "          password: ${{ secrets.GITHUB_TOKEN }}",
        "      - id: meta",
        f"        uses: {ACTIONS['docker/metadata-action']}",
        "        with:",
        "          images: ghcr.io/${{ github.repository }}",
        "          tags: |",
        "            type=semver,pattern={{version}}",
        "            type=semver,pattern={{major}}.{{minor}}",
        "            type=sha",
        f"      - uses: {ACTIONS['docker/build-push-action']}",
        "        with:",
        "          context: .",
        "          platforms: linux/amd64,linux/arm64",
        "          push: true",
        "          tags: ${{ steps.meta.outputs.tags }}",
        "          labels: ${{ steps.meta.outputs.labels }}",
        "          provenance: mode=max",
        "          sbom: true",
    ]
    return FileEntry(RELEASE_PATH, "\n".join(lines) + "\n")


def dependabot(ecosystems: list[str | tuple[str, str]]) -> FileEntry:
    """Weekly update PRs. Python packages are hash-locked; DEPLOY.md explains the refresh.

    Each entry is an ecosystem (checked at ``/``) or an ``(ecosystem, directory)`` pair.
    """
    lines = [
        "# Generated by mcp-wizard-generators. Python packages are pinned with hashes in",
        "# requirements.lock; refresh that file as DEPLOY.md / README describe.",
        "version: 2",
        "updates:",
    ]
    for entry in ecosystems:
        ecosystem, directory = (entry, "/") if isinstance(entry, str) else entry
        lines += [
            f"  - package-ecosystem: {ecosystem}",
            f"    directory: {directory}",
            "    schedule:",
            "      interval: weekly",
        ]
    return FileEntry(DEPENDABOT_PATH, "\n".join(lines) + "\n")


DEPLOY_PATH = ".github/workflows/deploy.yml"


def _push_image(name: str) -> list[str]:
    return [
        "      - id: ecr",
        f"        uses: {ACTIONS['aws-actions/amazon-ecr-login']}",
        f"      - uses: {ACTIONS['docker/setup-qemu-action']}",
        f"      - uses: {ACTIONS['docker/setup-buildx-action']}",
        "      - name: Build and push the ARM64 image",
        f"        uses: {ACTIONS['docker/build-push-action']}",
        "        with:",
        "          context: .",
        "          platforms: linux/arm64",
        "          push: true",
        f"          tags: ${{{{ steps.ecr.outputs.registry }}}}/{name}:${{{{ github.sha }}}}",
        "          # A single image manifest (no attestation index) for AgentCore.",
        "          provenance: false",
        "          sbom: false",
    ]


def _upload_package() -> list[str]:
    return [
        *_setup_python(f'"{AGENTCORE_CODE_PYTHON}"'),
        *_setup_uv(),
        "      - name: Package the server as an ARM64 zip and upload it",
        "        # From the repository root (the job default is deploy/terraform).",
        "        working-directory: .",
        "        run: |",
        f'          key="$(python {PACKAGE_SCRIPT})"',
        f'          aws s3 cp {ZIP_PATH} "s3://$CODE_BUCKET/$key"',
        '          echo "CODE_KEY=$key" >> "$GITHUB_ENV"',
    ]


def agentcore_deploy_workflow(
    caps: ServerCapabilities, *, name: str, code: bool = False
) -> FileEntry:
    """Build the ARM64 image and push it to ECR (or, with ``code``, package the zip and
    upload it to S3), then terraform plan + apply, all behind the protected
    ``production`` environment and with AWS credentials from OIDC."""
    variables = (
        "# AWS_DEPLOY_ROLE_ARN, AWS_REGION, TF_STATE_BUCKET and CODE_BUCKET (bootstrap outputs)."
        if code
        else "# AWS_DEPLOY_ROLE_ARN, AWS_REGION and TF_STATE_BUCKET (bootstrap outputs)."
    )
    env = (
        ["      CODE_BUCKET: ${{ vars.CODE_BUCKET }}"]
        if code
        else ["      IMAGE_TAG: ${{ github.sha }}"]
    )
    tf_var = '"code_key=$CODE_KEY"' if code else '"image_tag=$IMAGE_TAG"'
    lines = [
        "# Generated by mcp-wizard-generators. Deploys to AWS Bedrock AgentCore on every",
        '# push to main (DEPLOY.md, step "GitHub Actions"). Repository variables:',
        variables,
        "name: Deploy to AgentCore",
        "",
        "on:",
        "  push:",
        "    branches: [main]",
        "  workflow_dispatch:",
        "",
        "permissions:",
        "  contents: read",
        "  id-token: write",
        "",
        "concurrency:",
        "  group: deploy-production",
        "  cancel-in-progress: false",
        "",
        "jobs:",
        "  deploy:",
        "    runs-on: ubuntu-latest",
        "    # Add required reviewers to this environment to approve each deploy.",
        "    environment: production",
        "    env:",
        "      AWS_REGION: ${{ vars.AWS_REGION }}",
        "      TF_STATE_BUCKET: ${{ vars.TF_STATE_BUCKET }}",
        *env,
        "    defaults:",
        "      run:",
        "        working-directory: deploy/terraform",
        "    steps:",
        *_checkout(),
        f"      - uses: {ACTIONS['aws-actions/configure-aws-credentials']}",
        "        with:",
        "          role-to-assume: ${{ vars.AWS_DEPLOY_ROLE_ARN }}",
        "          aws-region: ${{ vars.AWS_REGION }}",
        *(_upload_package() if code else _push_image(name)),
        f"      - uses: {ACTIONS['hashicorp/setup-terraform']}",
        "        with:",
        f"          terraform_version: {TERRAFORM_VERSION}",
        "          terraform_wrapper: false",
        "      - name: Terraform init",
        "        run: >-",
        "          terraform init -input=false",
        '          -backend-config="bucket=$TF_STATE_BUCKET"',
        f'          -backend-config="key={name}/terraform.tfstate"',
        '          -backend-config="region=$AWS_REGION"',
        '          -backend-config="use_lockfile=true"',
        '          -backend-config="encrypt=true"',
        "      - name: Terraform plan",
        f"        run: terraform plan -input=false -var {tf_var} -out=tfplan",
        "      - name: Terraform apply",
        "        run: terraform apply -input=false tfplan",
        "      - name: Show the MCP endpoint",
        "        run: |",
        '          echo "MCP URL: $(terraform output -raw mcp_url)" >> "$GITHUB_STEP_SUMMARY"',
    ]
    return FileEntry(DEPLOY_PATH, "\n".join(lines) + "\n")
