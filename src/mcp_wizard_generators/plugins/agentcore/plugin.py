"""AWS Bedrock AgentCore + Python MCP server skeleton emitter."""

from __future__ import annotations

import json
from textwrap import dedent

from mcp_wizard_generators.models import FileEntry, FileTree, GenerateContext, ToolMapping


class AgentCorePythonPlugin:
    """
    MVP primary plugin (ADR-001).

    Emits a Python MCP server package plus AgentCore-oriented deploy stubs.
    Templates are intentionally minimal scaffolding — expand in follow-up PRs.
    """

    key = "agentcore"
    language = "python"
    display_name = "AWS Bedrock AgentCore (Python)"

    def generate(self, ctx: GenerateContext) -> FileTree:
        pkg = ctx.package_name
        tools = ctx.tool_map.tools
        entries: list[FileEntry] = [
            FileEntry("README.md", self._readme(ctx)),
            FileEntry("pyproject.toml", self._pyproject(pkg, ctx)),
            FileEntry(".env.example", self._env_example(ctx)),
            FileEntry(f"src/{pkg}/__init__.py", f'"""Generated MCP server for {ctx.ir.title}."""\n\n__version__ = "0.1.0"\n'),
            FileEntry(f"src/{pkg}/server.py", self._server(pkg, tools)),
            FileEntry(f"src/{pkg}/tools.py", self._tools_module(tools)),
            FileEntry(f"src/{pkg}/client.py", self._http_client(ctx)),
            FileEntry("deploy/agentcore/README.md", self._agentcore_deploy_readme()),
            FileEntry("deploy/agentcore/agent-config.stub.json", self._agentcore_config_stub(pkg, tools)),
            FileEntry("generation-manifest.json", json.dumps(self._manifest(ctx), indent=2) + "\n"),
        ]
        entries.extend(self._embed_agent_rules(ctx))
        return FileTree(entries=entries, root_name=pkg.replace("_", "-"))

    def _manifest(self, ctx: GenerateContext) -> dict:
        return {
            "target": self.key,
            "language": self.language,
            "title": ctx.ir.title,
            "version": ctx.ir.version,
            "tools": [
                {"name": t.tool_name, "operationId": t.operation_id, "method": t.method, "path": t.path}
                for t in ctx.tool_map.tools
            ],
            "security": {
                "authMode": ctx.security.auth_mode,
                "secretsStrategy": ctx.security.secrets_strategy,
            },
        }

    def _readme(self, ctx: GenerateContext) -> str:
        tool_lines = "\n".join(f"- `{t.tool_name}` — {t.description}" for t in ctx.tool_map.tools)
        return dedent(
            f"""\
            # {ctx.ir.title} MCP (AgentCore)

            Generated by **mcp-wizard-generators** for target `agentcore` (AWS Bedrock AgentCore).

            ## Tools

            {tool_lines or "(none)"}

            ## Run locally

            ```bash
            pip install -e .
            python -m {ctx.package_name}.server
            ```

            Configure upstream API base URL and credentials via environment variables
            (see `.env.example`). Deploy stubs live under `deploy/agentcore/`.
            """
        )

    def _pyproject(self, pkg: str, ctx: GenerateContext) -> str:
        return dedent(
            f"""\
            [build-system]
            requires = ["hatchling>=1.25"]
            build-backend = "hatchling.build"

            [project]
            name = "{pkg.replace('_', '-')}"
            version = "0.1.0"
            description = "Generated MCP server for {ctx.ir.title} (AgentCore)"
            requires-python = ">=3.11"
            dependencies = []

            [project.scripts]
            {pkg.replace('_', '-')}-mcp = "{pkg}.server:main"

            [tool.hatch.build.targets.wheel]
            packages = ["src/{pkg}"]
            """
        )

    def _env_example(self, ctx: GenerateContext) -> str:
        base = ctx.ir.servers[0] if ctx.ir.servers else "https://api.example.com"
        lines = [
            f"API_BASE_URL={base}",
            "# Auth mode from wizard security config: " + ctx.security.auth_mode,
        ]
        if ctx.security.auth_mode == "api_key":
            lines.append("API_KEY=replace-me")
        elif ctx.security.auth_mode == "oauth2":
            lines.extend(
                [
                    "OAUTH_TOKEN_URL=",
                    "OAUTH_CLIENT_ID=",
                    "OAUTH_CLIENT_SECRET=",
                    "OAUTH_SCOPES=",
                ]
            )
        lines.append("MCP_TRANSPORT=stdio")
        return "\n".join(lines) + "\n"

    def _server(self, pkg: str, tools: list[ToolMapping]) -> str:
        tool_regs = "\n".join(
            f'    register_tool("{t.tool_name}", TOOLS["{t.tool_name}"])' for t in tools
        )
        return dedent(
            f'''\
            """MCP server entrypoint (stdio skeleton).

            Replace register_tool / run_stdio with the pinned MCP Python SDK
            once the SDK pinning decision lands (system design open decision #4).
            """

            from __future__ import annotations

            from {pkg}.tools import TOOLS


            def register_tool(name: str, handler: dict) -> None:
                """Stub registration hook for the MCP SDK."""
                _ = name, handler


            def run_stdio() -> None:
                """Stub transport loop — wire to MCP SDK stdio server."""
                print("mcp-wizard skeleton: stdio server not yet bound to an MCP SDK")


            def main() -> None:
            '''
        ) + (
            (tool_regs + "\n") if tool_regs else "    pass\n"
        ) + "    run_stdio()\n\n\nif __name__ == \"__main__\":\n    main()\n"

    def _tools_module(self, tools: list[ToolMapping]) -> str:
        payload = {
            t.tool_name: {
                "description": t.description,
                "inputSchema": t.input_schema,
                "upstream": {"method": t.method.upper(), "path": t.path},
                "operationId": t.operation_id,
            }
            for t in tools
        }
        body = json.dumps(payload, indent=2)
        return (
            '"""MCP tool definitions derived from OpenAPI IR."""\n\n'
            "from __future__ import annotations\n\n"
            f"TOOLS = {body}\n"
        )

    def _http_client(self, ctx: GenerateContext) -> str:
        return dedent(
            f'''\
            """Upstream OpenAPI HTTP client stub.

            Auth mode: {ctx.security.auth_mode}
            Secrets strategy: {ctx.security.secrets_strategy}
            """

            from __future__ import annotations

            import os
            from typing import Any


            def request(method: str, path: str, *, json_body: dict[str, Any] | None = None) -> dict[str, Any]:
                base = os.environ.get("API_BASE_URL", "").rstrip("/")
                url = f"{{base}}{{path}}"
                # Skeleton only — real HTTP + auth adapters land in a later PR.
                return {{"_skeleton": True, "method": method, "url": url, "json": json_body}}
            '''
        )

    def _agentcore_deploy_readme(self) -> str:
        return dedent(
            """\
            # AWS Bedrock AgentCore deploy stubs

            This directory holds **scaffolding only** for AWS Bedrock AgentCore wiring.

            Planned contents (later PRs):

            - Agent / runtime config fragments aligned with Bedrock AgentCore docs
            - IAM / Secrets Manager reference patterns (no live secrets)
            - Packaging notes for publishing the MCP server for AgentCore consumption

            Do not treat `agent-config.stub.json` as a production AgentCore schema —
            it is a placeholder for golden tests and API integration.
            """
        )

    def _agentcore_config_stub(self, pkg: str, tools: list[ToolMapping]) -> str:
        stub = {
            "schemaVersion": "stub-0.1",
            "target": "aws.bedrock.agentcore",
            "mcpServer": {
                "package": pkg,
                "entrypoint": f"{pkg}.server:main",
                "transport": "stdio",
            },
            "tools": [t.tool_name for t in tools],
            "notes": "Placeholder — replace with real AgentCore config shape when pinned.",
        }
        return json.dumps(stub, indent=2) + "\n"

    def _embed_agent_rules(self, ctx: GenerateContext) -> list[FileEntry]:
        entries: list[FileEntry] = []
        for rel, text in sorted(ctx.agent_rules.originals.items()):
            # Preserve conventional layouts when paths already look Cursor/Anthropic-shaped.
            path = rel.lstrip("/")
            if not (
                path.startswith(".cursor/")
                or path.startswith(".claude/")
                or path.endswith("CLAUDE.md")
                or path.endswith("AGENTS.md")
                or path.endswith(".cursorrules")
            ):
                path = f"agent-rules/{path}"
            entries.append(FileEntry(path, text if text.endswith("\n") else text + "\n"))
        return entries
